#create an OpenAI client object using OpenAI class
client= OpenAI(api_key=api_key) 

#1)first to summarize text
#define a  api view function to handle the  post request
#use the @api_view decorator to specify that this view function only accepts POST requests

 

#  1)summarize content
@api_view(['POST']) 
def summarize(request):
    #get the post parameter that the user is sending
    userquery = request.data.get('userquery') #request.data is a dictionary that contains the data sent in the request body. 
    #get method is used to get the value of the key 'userquery' from the dictionary. If the key is not present, it returns an empty string.
    
    #check if the userquery is empty
    if not userquery:
        return Response({'error': 'No user query provided'}, status=400) #if userquery is empty, return an error response with status code 400 (bad request)

    #create a custom prompt to make the gpt behave  like a summarizer. The prompt is a string that contains the instructions for the model.
    #use the OpenAI client to generate a summary of the userquery

    prompt = f'''you are a professional summarization system.now,summarze the following text.
    Instructions:
    -maximum 100 words in the ouitput
    -make sure to include the main ideas
    -do not add any extra information other than the given one
    -use plain and simple english
    Text: {userquery}
    '''

    #send this prompt to the OpenAI API and get the response.
    #pass this prompt to the API using the client.response.create() request
    #it will give back response
    response=client.responses.create(model="gpt-6-luna",input = prompt)

    #send the response from GPT back to the user as a json   

    return Response({'summary': response.output_text},status=200) #response.output_text is the text generated by the model. It is a string that contains the summary of the userquery.
    





